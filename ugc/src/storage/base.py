"""Интерфейс очереди событий.

Бизнес-логика сбора знает, что принятые события нужно куда-то положить, и не
знает, что это Kafka: в тестах на её место встаёт очередь в памяти, а в
продакшене Kafka можно будет заменить, не трогая слой services.

Контракт для всех реализаций: сбой хранилища выходит наружу как
`QueueUnavailableError`, а не как исключение библиотеки. API отвечает на него
503 и пишет причину в журнал; клиент не удаляет события из своей очереди и
повторит их позже.
"""

from abc import ABC, abstractmethod
from collections.abc import Sequence
from dataclasses import dataclass


class QueueUnavailableError(Exception):
    """Очередь не приняла события: брокер недоступен, таймаут или отказ записи."""


@dataclass(frozen=True)
class QueuedEvent:
    """Событие, готовое к отправке.

    `key` определяет партицию: события одной сессии просмотра попадают в одну
    партицию и приходят потребителю по порядку. `value` — уже сериализованное
    тело: сериализовать его должен тот, кто знает контракт, а не транспорт.
    """

    key: str
    value: bytes


class EventQueue(ABC):
    """Очередь, в которую складываются принятые события."""

    @abstractmethod
    def publish(self, events: Sequence[QueuedEvent]) -> None:
        """Отправляет пачку событий и ждёт подтверждения записи.

        Возврат из метода означает, что события записаны и переживут падение
        сервиса приёма: клиенту можно отвечать «принято».

        Raises:
            QueueUnavailableError: события записать не удалось.
        """

    @abstractmethod
    def is_ready(self) -> bool:
        """Готова ли очередь принимать события — для проверки готовности контейнера."""

    @abstractmethod
    def close(self) -> None:
        """Дописывает буфер и освобождает соединения при остановке сервиса."""
