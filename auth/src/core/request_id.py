"""Идентификатор запроса, общий для всей цепочки сервисов.

Запрос к кинотеатру проходит через несколько сервисов, и логи каждого сами по
себе ничего не рассказывают о запросе целиком. Поэтому nginx выдаёт каждому
входящему запросу идентификатор и передаёт его заголовком `X-Request-Id`, а
каждый сервис пишет его в свои записи журнала и передаёт дальше, в исходящие
вызовы. По одному идентификатору собирается вся история запроса.

Идентификатор задаёт nginx, а не клиент: `$request_id` он генерирует сам и
перезаписывает им присланный заголовок. Иначе клиент мог бы слить свои запросы
с чужими в журнале или замусорить поиск.

Хранится он в контекстной переменной: она своя у каждой задачи asyncio,
поэтому одновременные запросы не перепутают идентификаторы, а функции в
глубине не приходится тащить его параметром.
"""

import logging
from contextvars import ContextVar

HEADER = 'X-Request-Id'
# Записи вне обработки запроса (старт сервиса, фоновые задачи) идентификатора
# не имеют; в журнале это видно как «-».
NO_REQUEST = '-'

_request_id: ContextVar[str] = ContextVar('request_id', default=NO_REQUEST)


def set_request_id(request_id: str) -> None:
    _request_id.set(request_id)


def get_request_id() -> str:
    return _request_id.get()


class RequestIdFilter(logging.Filter):
    """Подставляет идентификатор запроса в каждую запись журнала."""

    def filter(self, record: logging.LogRecord) -> bool:
        record.request_id = get_request_id()
        return True
