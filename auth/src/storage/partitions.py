"""Секции таблицы истории входов: имена и границы.

История входов растёт вдоль оси времени — по заданию это миллионы записей, —
поэтому она разбита на месячные секции (RANGE по `created_at`). Что это даёт:

* **Чистка отсечением.** Год истории удаляется `DROP TABLE` одной секции, а не
  построчным `DELETE` по миллионам строк; секцию можно и `DETACH` — отцепить,
  выгрузить в архив и удалить уже спокойно.
* **Горячие данные отдельно от холодных.** Запросы почти всегда идут за
  последними входами, то есть в одну-две свежие секции; их индексы невелики и
  целиком помещаются в память.
* **Обслуживание по частям.** VACUUM, REINDEX и резервное копирование работают
  с секцией, а не с таблицей целиком.

Почему не по типу устройства, как в примере урока: таких секций было бы три-четыре,
они не уменьшаются со временем и делят таблицу поперёк её роста — чтение истории
одного пользователя всё равно задело бы каждую. Таблица растёт по времени, и
делить её стоит по нему же. Почему не по `user_id` (HASH): каждый запрос попадал
бы ровно в одну секцию, но старые записи не удалить отсечением, а чистка истории
за давние периоды — то, ради чего секции здесь и нужны.

Чтение истории одного пользователя фильтра по дате не содержит, поэтому секции
не отсекаются по условию. Зато в каждой есть индекс `(user_id, created_at)`, а
выдача постраничная: PostgreSQL сливает отсортированные потоки из секций
(MergeAppend) и останавливается, набрав страницу, — до старых секций дело обычно
не доходит.

Секции на будущие месяцы создаются заранее (`cli.py create-login-partitions`).
Если этого не сделать, записи попадут в секцию по умолчанию и не потеряются:
она страхует от пропущенного обслуживания. В большом проекте эту работу берёт
на себя расширение pg_partman.
"""

from collections.abc import Iterator
from datetime import date

TABLE = 'login_history'
# Секция по умолчанию: сюда попадают входы за месяцы, для которых секцию не
# создали. Без неё вставка в такой месяц завершилась бы ошибкой.
DEFAULT_PARTITION = f'{TABLE}_default'


def month_start(day: date) -> date:
    """Первое число месяца, которому принадлежит дата."""
    return day.replace(day=1)


def next_month(month: date) -> date:
    """Первое число следующего месяца."""
    if month.month == 12:
        return month.replace(year=month.year + 1, month=1, day=1)
    return month.replace(month=month.month + 1, day=1)


def partition_name(month: date) -> str:
    """Имя секции месяца: login_history_y2026m09."""
    return f'{TABLE}_y{month.year:04d}m{month.month:02d}'


def partition_bounds(month: date) -> tuple[date, date]:
    """Границы секции: от первого числа месяца включительно до первого числа следующего."""
    start = month_start(month)
    return start, next_month(start)


def months_from(start: date, count: int) -> Iterator[date]:
    """Первые числа `count` месяцев подряд, начиная с месяца даты `start`."""
    month = month_start(start)
    for _ in range(count):
        yield month
        month = next_month(month)
