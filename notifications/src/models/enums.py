"""Перечисления предметной области.

Строковые значения, а не числа: они уезжают в очередь и в API, а урок про
отчётные события прямо предупреждает, что смена представления enum с числа на
строку ломает всех потребителей. Начинаем сразу со строк, чтобы не менять.
"""

from enum import Enum


class Channel(str, Enum):
    """Способ доставки.

    Реализован email; websocket доставляет уведомление в открытую вкладку.
    SMS и push перечислены намеренно: по ним видно, что канал — это значение,
    а не зашитое в код предположение, и добавление нового не трогает ни API,
    ни планировщик (НФТ-12).
    """

    EMAIL = 'email'
    WEBSOCKET = 'websocket'
    SMS = 'sms'
    PUSH = 'push'


class Urgency(str, Enum):
    """Мгновенное уведомление или откладываемое.

    Мгновенные уходят сразу (новая серия, чек об оплате), откладываемые
    копятся и отправляются не чаще, чем разрешает тип уведомления, — иначе
    сотня лайков за сутки превратится в сотню писем.
    """

    INSTANT = 'instant'
    DEFERRED = 'deferred'


class DeliveryStatus(str, Enum):
    """Что стало с одним письмом.

    `PENDING` — письмо ещё не отправлено: либо его отправляют прямо сейчас
    (у записи действует аренда), либо прошлая попытка не удалась и его можно
    забрать снова. Окончательные состояния — `SENT`, `FAILED` и `SKIPPED`:
    письмо с таким ключом больше не отправляется.
    """

    PENDING = 'pending'
    SENT = 'sent'
    FAILED = 'failed'
    SKIPPED = 'skipped'


class ClaimState(str, Enum):
    """Чем закончилась попытка забрать письмо на отправку."""

    # Письмо наше: отправляем.
    CLAIMED = 'claimed'
    # Письмо уже в окончательном состоянии: отправлено, отклонено или отменено.
    DONE = 'done'
    # Письмо прямо сейчас отправляет другой отправитель — его аренда ещё идёт.
    BUSY = 'busy'


class CampaignStatus(str, Enum):
    """Состояние рассылки менеджера."""

    DRAFT = 'draft'
    SCHEDULED = 'scheduled'
    RUNNING = 'running'
    DONE = 'done'
    CANCELLED = 'cancelled'


class AudienceKind(str, Enum):
    """Кому адресовано событие.

    `ALL` разворачивается постраничным обходом справочника контактов, `USERS` —
    готовым списком, `SEGMENT` — правилом, которое разворачивает планировщик.
    В сообщении едет именно правило, а не список адресатов: миллион
    идентификаторов в теле сообщения не поместится, да и не должен.
    """

    USERS = 'users'
    ALL = 'all'
    SEGMENT = 'segment'
