"""Канал доставки — то, что отличает письмо от эсэмэски.

Задание требует, чтобы систему можно было расширить на SMS и push, а
реализован был email. Поэтому канал — это интерфейс с одним методом, а выбор
конкретного лежит в настройках типа уведомления и в подписке зрителя. Ни API,
ни планировщик, ни админ-панель о каналах ничего не знают: добавление нового —
это новая реализация и новый воркер-отправщик, а не правки по всему сервису
(НФТ-12).
"""

from abc import ABC, abstractmethod

from models.enums import Channel
from models.notification import RenderedMessage


class ChannelUnavailableError(Exception):
    """Канал временно не работает: сообщение нужно повторить позже.

    Отделено от ошибки в самом сообщении намеренно: недоступность лечится
    ожиданием, а негодный адрес — нет, и повторять его бессмысленно.
    """


class MessageRejectedError(Exception):
    """Канал отказался от сообщения навсегда: негодный адрес, запрет получателя.

    Повторять нельзя: сколько ни жди, адрес не станет существующим.
    """


class DeliveryChannel(ABC):
    """Отправка готового сообщения."""

    @property
    @abstractmethod
    def channel(self) -> Channel:
        """Какой канал реализует."""

    @abstractmethod
    async def send(self, message: RenderedMessage) -> None:
        """Отправляет сообщение.

        Raises:
            ChannelUnavailableError: канал временно не работает.
            MessageRejectedError: сообщение негодно и повтору не подлежит.
        """

    async def close(self) -> None:  # noqa: B027 - намеренно не абстрактный
        """Освобождает ресурсы канала.

        Не абстрактный намеренно: закрывать нечего почти всем каналам, и
        требовать от каждого пустую реализацию — лишний шум.
        """
