"""Интерфейс проверки прав пользователя во внешнем сервисе авторизации.

Сервисы спрашивают «есть ли у владельца этого токена такое право» и не знают
ни про HTTP, ни про JWT, ни про то, что сервис авторизации вообще существует
отдельно. Поэтому проверку можно заменить другой реализацией — например,
разбором токена на месте — не трогая бизнес-логику.

Контракт для всех реализаций: сбой внешнего сервиса выходит наружу как
AccessUnavailableError, а не как ошибка библиотеки, и не маскируется под
«права нет». Решать, что делать без ответа сервиса авторизации, должен
вызывающий код: отказ в доступе и временная невозможность его проверить —
разные ситуации.
"""

from abc import ABC, abstractmethod


class AccessUnavailableError(Exception):
    """Сервис авторизации не смог ответить: сбой сети, таймаут, 5xx или открытый прерыватель."""


class TokenRejectedError(Exception):
    """Сервис авторизации отклонил токен: он истёк, повреждён или его сессия закрыта.

    Несёт машиночитаемый код ошибки сервиса авторизации, чтобы клиент узнал,
    обновлять ли пару токенов или входить заново.
    """

    def __init__(self, code: str, detail: str):
        super().__init__(detail)
        self.code = code
        self.detail = detail


class AccessGateway(ABC):
    """Проверка прав пользователя по его токену."""

